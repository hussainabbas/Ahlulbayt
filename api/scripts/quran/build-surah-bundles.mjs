#!/usr/bin/env node
/**
 * Build mobile SurahBundle files from the pinned Tanzil text.
 *
 * Output is fully deterministic (no timestamps), so every bundle has a stable
 * SHA-256 that is recorded in manifest.json and enforced by quran:validate.
 */
import { readFileSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { SURAH_COUNT } from './canonical-ayah-counts.mjs';
import {
  BUNDLE_VERSION,
  buildSurahBundle,
  checkSourceStructure,
  loadPinnedSource,
  parseTanzilMetadata,
  serializeBundle,
  sha256,
  surahFileName,
} from './corpus-lib.mjs';
import { loadSurahMetadata } from './load-surah-metadata.mjs';
import {
  BUNDLES_DIR,
  MANIFEST_PATH,
  MOBILE_GENERATED_DIR,
  TANZIL_ATTRIBUTION,
  TANZIL_METADATA_PATH,
  TANZIL_RAW_PATH,
} from './paths.mjs';

function registrySource(surahNumbers) {
  const loaders = surahNumbers
    .map((n) => `  ${n}: () => require('./${surahFileName(n)}') as SurahBundle,`)
    .join('\n');

  return `/** AUTO-GENERATED by api/scripts/quran/build-surah-bundles.mjs — do not edit. */
/* eslint-disable @typescript-eslint/no-require-imports */
import type { SurahBundle } from '../../../types';

export const GENERATED_CORPUS_READY = true;

export const GENERATED_SURAH_COUNT = ${surahNumbers.length};

/** Arabic text source for every bundled surah. */
export const GENERATED_CORPUS_SOURCE = '${TANZIL_ATTRIBUTION}';

/** One loader per surah so a surah's JSON is only evaluated when it is first opened. */
const LOADERS: Record<number, () => SurahBundle> = {
${loaders}
};

const loaded = new Map<number, SurahBundle>();

export function loadGeneratedSurah(number: number): SurahBundle | undefined {
  const cached = loaded.get(number);
  if (cached) return cached;
  const loader = LOADERS[number];
  if (!loader) return undefined;
  const bundle = loader();
  loaded.set(number, bundle);
  return bundle;
}

export const GENERATED_SURAH_NUMBERS: number[] = Object.keys(LOADERS).map(Number);

/** Lazy view over the corpus: reading a key loads that surah only. */
export const GENERATED_SURAHS: Record<number, SurahBundle> = Object.defineProperties(
  {},
  Object.fromEntries(
    GENERATED_SURAH_NUMBERS.map((number) => [
      number,
      { enumerable: true, get: () => loadGeneratedSurah(number) },
    ]),
  ),
) as Record<number, SurahBundle>;
`;
}

async function main() {
  let manifest;
  try {
    manifest = JSON.parse(await readFile(MANIFEST_PATH, 'utf8'));
  } catch {
    throw new Error(`Missing manifest at ${MANIFEST_PATH}. Run npm run quran:fetch first.`);
  }

  const source = loadPinnedSource(TANZIL_RAW_PATH, manifest);
  const sourceErrors = [...source.errors, ...checkSourceStructure(source.bySurah)];
  if (sourceErrors.length) {
    throw new Error(
      `Refusing to build from an unverified source:\n- ${sourceErrors
        .map((e) => `${e.code} ${e.ref}: ${e.detail}`)
        .join('\n- ')}`,
    );
  }

  const tanzilMeta = parseTanzilMetadata(readFileSync(TANZIL_METADATA_PATH, 'utf8'));
  const metadata = loadSurahMetadata();

  await mkdir(BUNDLES_DIR, { recursive: true });
  await mkdir(MOBILE_GENERATED_DIR, { recursive: true });

  const built = [];
  const bundleHashes = {};
  for (let surah = 1; surah <= SURAH_COUNT; surah += 1) {
    const meta = metadata.find((row) => row.number === surah);
    if (!meta) throw new Error(`Missing metadata for surah ${surah}`);

    const bundle = buildSurahBundle(meta, source.bySurah.get(surah), tanzilMeta, TANZIL_ATTRIBUTION);
    const json = serializeBundle(bundle);

    await writeFile(join(BUNDLES_DIR, surahFileName(surah)), json, 'utf8');
    await writeFile(join(MOBILE_GENERATED_DIR, surahFileName(surah)), json, 'utf8');
    bundleHashes[String(surah)] = sha256(json);
    built.push(surah);
  }

  await writeFile(join(MOBILE_GENERATED_DIR, 'registry.ts'), registrySource(built), 'utf8');

  const nextManifest = {
    ...manifest,
    bundleVersion: BUNDLE_VERSION,
    bundlePath: 'mobile/src/features/quran/data/bundled/generated/',
    bundles: bundleHashes,
  };
  await writeFile(MANIFEST_PATH, `${JSON.stringify(nextManifest, null, 2)}\n`, 'utf8');

  console.log(`Built ${built.length} surah bundles (bundle version ${BUNDLE_VERSION}).`);
  console.log(`Mobile bundles: ${MOBILE_GENERATED_DIR}`);
  console.log('Run npm run quran:validate to verify.');
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
